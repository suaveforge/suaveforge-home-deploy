const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path');
const OUT=path.resolve(__dirname,'artifacts');fs.mkdirSync(OUT,{recursive:true});
const BASE='http://127.0.0.1:8181';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-webgl','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
 const errors=[],report={};
 try{
 const page=await browser.newPage({viewport:{width:1440,height:980},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push('desktop: '+e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push('desktop console: '+m.text())});
 const response=await page.goto(BASE+'/research/interactive/',{waitUntil:'domcontentloaded',timeout:45000});
 report.http=response.status();
 await page.waitForFunction(()=>document.querySelectorAll('.ref').length===24,null,{timeout:13000});
 await page.waitForFunction(()=>document.querySelector('[data-spatial-viewport]')?.dataset.webglReady==='true',{timeout:35000});
 report.desktop={entries:await page.locator('.ref').count(),webgl:await page.locator('[data-spatial-viewport]').getAttribute('data-webgl-ready'),initial:await page.evaluate(()=>window.__sfInteractiveQA.snapshot()),categories:{}};
 for(const name of ['spatial','product','motion','graphics','data']){
  await page.locator('[data-catalog-filter="'+name+'"]').click();
  report.desktop.categories[name]=await page.locator('.ref').count();
 }
 await page.locator('[data-catalog-filter="all"]').click();
 await page.locator('[data-catalog-search]').fill('WebGL');
 report.desktop.searchCount=await page.locator('.ref').count();
 await page.locator('[data-catalog-search]').fill('');
 const snapshot=()=>page.evaluate(()=>window.__sfInteractiveQA.snapshot());
 await page.locator('[data-theme="power"]').click();await page.waitForTimeout(300);
 report.desktop.power=await snapshot();
 await page.locator('[data-theme="hvac"]').click();await page.waitForTimeout(300);
 report.desktop.hvac=await snapshot();
 await page.locator('[data-theme="safety"]').click();await page.waitForTimeout(300);
 report.desktop.safety=await snapshot();
 await page.locator('[data-floor="3"]').click();await page.waitForTimeout(280);
 report.desktop.floor=await snapshot();
 const levelsBefore=report.desktop.floor.levels;
 await page.locator('[data-explode]').click();await page.waitForTimeout(580);
 report.desktop.exploded=await snapshot();
 report.desktop.floorSeparation=report.desktop.exploded.levels[4]-report.desktop.exploded.levels[0]>(levelsBefore[4]-levelsBefore[0])+.65;
 await page.locator('[data-theme="structure"]').click();
 await page.locator('[data-floor="-1"]').click();await page.waitForTimeout(450);
 await page.locator('[data-explode]').click();await page.waitForTimeout(450);
 const beforeRotate=await snapshot();await page.locator('[data-motion="rotate"]').click();await page.waitForTimeout(480);
 report.desktop.rotated=(await snapshot()).rotation-beforeRotate.rotation>.30;
 await page.locator('[data-motion="move"]').click();await page.waitForTimeout(355);
 report.desktop.moved=Math.abs((await snapshot()).position)>.08;
 await page.locator('[data-motion="scale"]').click();await page.waitForTimeout(350);
 report.desktop.scaled=(await snapshot()).scale>1.04;
 await page.locator('[data-reset]').click();await page.waitForTimeout(500);
 await page.screenshot({path:path.join(OUT,'building-desktop.png'),fullPage:true,animations:'disabled'});
 await page.locator('[data-scene-mode="equipment"]').click();await page.waitForTimeout(600);
 report.desktop.equipment=await snapshot();
 await page.locator('[data-explode]').click();await page.waitForTimeout(600);
 report.desktop.equipmentExploded=await snapshot();
 report.desktop.equipmentSeparated=report.desktop.equipmentExploded.parts[4]-report.desktop.equipmentExploded.parts[0]>(report.desktop.equipment.parts[4]-report.desktop.equipment.parts[0])+.55;
 await page.screenshot({path:path.join(OUT,'equipment-desktop.png'),fullPage:true,animations:'disabled'});
 await page.locator('[data-scene-mode="building"]').click();
 await page.locator('[data-theme="hvac"]').click();
 await page.locator('[data-explode]').click();await page.waitForTimeout(650);
 await page.screenshot({path:path.join(OUT,'building-hvac-exploded.png'),fullPage:true,animations:'disabled'});
 report.desktop.noOverflow=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2);
 report.homeLink=await page.locator('a[href="/research/"]').count();
 const site=await browser.newPage({viewport:{width:1440,height:900}});
 await site.goto(BASE+'/',{waitUntil:'domcontentloaded',timeout:45000});
 report.desktopMenu=await site.locator('#mega-research a[href="/research/interactive/"]').count();
 report.mobileMenu=await site.locator('#mobile-research a[href="/research/interactive/"]').count();
 const research=await browser.newPage({viewport:{width:1440,height:900}});
 await research.goto(BASE+'/research/',{waitUntil:'domcontentloaded',timeout:45000});
 report.researchTile=await research.locator('.research-tiles a[href="/research/interactive/"]').count();
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push('mobile: '+e.message));mobile.on('console',m=>{if(m.type()==='error')errors.push('mobile console: '+m.text())});
 await mobile.goto(BASE+'/research/interactive/',{waitUntil:'domcontentloaded',timeout:45000});
 await mobile.waitForFunction(()=>document.querySelector('[data-spatial-viewport]')?.dataset.webglReady==='true',{timeout:35000});
 await mobile.locator('[data-theme="power"]').click();
 await mobile.locator('[data-floor="2"]').click();
 await mobile.locator('[data-explode]').click();
 await mobile.waitForTimeout(550);
 report.mobile={state:await mobile.evaluate(()=>window.__sfInteractiveQA.snapshot()),entries:await mobile.locator('.ref').count(),overflow:await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)};
 report.mobile.navSingleLine=await mobile.locator('.nav a:visible').evaluateAll(nodes=>nodes.length>=3&&nodes.every(el=>getComputedStyle(el).whiteSpace==='nowrap')&&new Set(nodes.map(el=>Math.round(el.getBoundingClientRect().top))).size===1);
 await mobile.evaluate(()=>window.scrollTo(0,0));await mobile.waitForTimeout(300);
 await mobile.screenshot({path:path.join(OUT,'building-mobile.png'),fullPage:true,animations:'disabled'});
 const s=report.desktop;
 const passed=report.http===200&&s.webgl==='true'&&s.initial.sceneObjects>=80&&s.initial.pickable>=25&&s.entries===24&&Object.values(s.categories).every(n=>n>0)&&s.searchCount>=2&&s.power.theme==='power'&&s.hvac.theme==='hvac'&&s.safety.theme==='safety'&&s.floor.floor===3&&s.floorSeparation&&s.rotated&&s.moved&&s.scaled&&s.equipment.mode==='equipment'&&s.equipmentSeparated&&s.noOverflow&&report.mobile.state.theme==='power'&&report.mobile.state.floor===2&&report.mobile.state.explode&&report.mobile.entries===24&&!report.mobile.overflow&&report.mobile.navSingleLine&&report.desktopMenu===1&&report.mobileMenu===1&&report.researchTile===1&&errors.length===0;
 const result={pass:passed,details:report,errors};fs.writeFileSync(path.join(OUT,'qa-report.json'),JSON.stringify(result,null,2)+'\n');
 console.log('INTERACTIVE_LAB_QA',JSON.stringify({pass:passed,http:report.http,catalog:24,webgl:s.webgl,modelCount:s.initial.sceneObjects,themeTests:[s.power.theme,s.hvac.theme,s.safety.theme],floor:s.floor.floor,separation:s.floorSeparation,rotation:s.rotated,position:s.moved,scale:s.scaled,equipment:s.equipment.mode,equipmentSeparated:s.equipmentSeparated,mobile:report.mobile,menu:[report.desktopMenu,report.mobileMenu],researchTile:report.researchTile,errors}));
 if(!passed)process.exitCode=1;
 }finally{await browser.close()}
})().catch(e=>{console.error('INTERACTIVE_LAB_QA_FATAL',e.stack||e);process.exitCode=1});