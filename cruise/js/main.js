// =====================
// 필터
// =====================
function filterCruises(region) {
  currentFilter = region;
  document.querySelectorAll(".filter-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.filter === region);
  });
  applyFilters();
}

function applyFilters() {
  let list = cruises;
  if (currentFilter !== "all") list = list.filter(c => c.region === currentFilter);
  if (searchQuery) {
    const q = searchQuery.toLowerCase();
    list = list.filter(c =>
      g(c.title).toLowerCase().includes(q) ||
      c.line.toLowerCase().includes(q) ||
      g(c.route).toLowerCase().includes(q)
    );
  }
  renderCruises(list);
}

// =====================
// 검색
// =====================
function handleSearch() {
  const input = document.getElementById("searchInput");
  const regionSelect = document.getElementById("regionSelect");
  searchQuery = input ? input.value.trim() : "";
  if (regionSelect?.value) {
    currentFilter = regionSelect.value;
    document.querySelectorAll(".filter-btn").forEach(btn => {
      btn.classList.toggle("active", btn.dataset.filter === currentFilter);
    });
  }
  applyFilters();
  document.getElementById("deals")?.scrollIntoView({ behavior: "smooth" });
}

function goToCruise(id) { window.location.href = `cruise.html?id=${id}`; }

function openAffiliate(id) {
  const cruise = cruises.find(c => c.id === id);
  if (!cruise) return;
  showToast(t("toast.redirect"));
  setTimeout(() => window.open(cruise.affiliateUrl, "_blank"), 800);
}

function goToRegion(region) {
  filterCruises(region);
  document.getElementById("deals")?.scrollIntoView({ behavior: "smooth" });
}

// =====================
// Toast
// =====================
function showToast(msg) {
  let toast = document.getElementById("toast");
  if (!toast) {
    toast = document.createElement("div");
    toast.id = "toast"; toast.className = "toast";
    document.body.appendChild(toast);
  }
  toast.textContent = msg;
  toast.classList.add("show");
  setTimeout(() => toast.classList.remove("show"), 2500);
}

