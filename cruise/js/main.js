let currentLang = localStorage.getItem("lang") || "en";

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("lang", lang);
  applyLang();
  // 동적 렌더링 다시
  if (document.getElementById("cruiseGrid")) applyFilters();
  if (document.getElementById("lineGrid")) renderCruiseLines(document.getElementById("lineGrid"));
  if (document.getElementById("cruiseDetail")) loadCruiseDetail();
  if (document.getElementById("lineDetail")) loadLineDetail();
  // 언어 버튼 상태
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

function t(key) {
  return i18n[currentLang]?.[key] || i18n["ko"][key] || key;
}

function applyLang() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (el.tagName === "INPUT") {
      el.placeholder = val;
    } else {
      el.innerHTML = val;
    }
  });
  // select options
  const regionSelect = document.getElementById("regionSelect");
  if (regionSelect) {
    regionSelect.options[0].text = t("search.all");
    const regionKeys = ["mediterranean","caribbean","alaska","asia","europe","middleeast"];
    regionKeys.forEach((r, i) => {
      if (regionSelect.options[i+1]) regionSelect.options[i+1].text = t(`search.${r}`);
    });
  }
  // filter buttons
  document.querySelectorAll(".filter-btn[data-filter]").forEach(btn => {
    const f = btn.dataset.filter;
    btn.innerHTML = t(f === "all" ? "filter.all" : `filter.${f}`);
  });
  // html lang attr
  document.documentElement.lang = currentLang === "ko" ? "ko" : "en";
}

