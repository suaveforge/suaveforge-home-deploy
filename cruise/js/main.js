// =====================
// 현재 언어 헬퍼
// =====================
function g(obj) {
  if (typeof obj === "string") return obj;
  return obj?.[currentLang] || obj?.["ko"] || "";
}

// =====================
// State
// =====================
let currentFilter = "all";
let searchQuery = "";

// =====================
// 크루즈 카드 렌더링
// =====================
function renderCruises(list) {
  const grid = document.getElementById("cruiseGrid");
  if (!grid) return;
  if (list.length === 0) {
    grid.innerHTML = `<div style="grid-column:1/-1;text-align:center;padding:60px 20px;color:var(--text-light);">
      <div style="font-size:48px;margin-bottom:16px;">🔍</div>
      <p style="font-size:16px;font-weight:600;">${currentLang === "ko" ? "검색 결과가 없습니다." : "No results found."}</p>
    </div>`;
    return;
  }
  grid.innerHTML = list.map(c => {
    const discount = Math.round((1 - c.price / c.originalPrice) * 100);
    const badgeClass = c.badge === "NEW" ? "new" : c.badge === "BEST" ? "best" : "";
    const nights = c.nights;
    const nightsLabel = currentLang === "ko" ? `${nights}박 ${nights+1}일` : `${nights}N/${nights+1}D`;
    return `
    <div class="cruise-card" onclick="goToCruise(${c.id})">
      <div class="card-image" style="background:${c.bg}">
        <div class="card-image-placeholder">${c.emoji}</div>
        <span class="card-badge ${badgeClass}">${c.badge === "SALE" ? `${discount}% OFF` : c.badge}</span>
        <span class="card-nights">${nightsLabel}</span>
      </div>
      <div class="card-body">
        <div class="card-line">${c.line}</div>
        <div class="card-title">${g(c.title)}</div>
        <div class="card-route">${g(c.route)}</div>
        <div class="card-footer">
          <div class="card-price">
            <span class="price-from">${t("card.from")}</span>
            <span class="price-amount">₩${c.price.toLocaleString()}</span>
            <span class="price-unit"> ${t("card.unit")}</span>
          </div>
          <button class="card-btn" onclick="event.stopPropagation();openAffiliate(${c.id})">${t("card.btn")}</button>
        </div>
      </div>
    </div>`;
  }).join("");
}

